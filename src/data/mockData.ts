export function computeSiagaStatus(
  waterLevelM: number,
  commOnline: boolean,
  thresholds: Station['thresholds'],
  type: Station['type'],
  rainfallMmH: number
): SiagaLevel {
  if (!commOnline) return 'offline';
  if (type === 'ARR' || type === 'AWS') {
    if (rainfallMmH >= thresholds.rainExtremeMmH) return 'siaga2';
    if (rainfallMmH >= thresholds.rainExtremeMmH * 0.65) return 'siaga3';
    if (rainfallMmH >= thresholds.rainExtremeMmH * 0.35) return 'siaga4';
    return 'normal';
  }
  if (waterLevelM >= thresholds.siaga1) return 'siaga1';
  if (waterLevelM >= thresholds.siaga2) return 'siaga2';
  if (waterLevelM >= thresholds.siaga3) return 'siaga3';
  if (waterLevelM >= thresholds.siaga4) return 'siaga4';
  return 'normal';
}

