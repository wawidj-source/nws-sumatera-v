export function generateStationSeries(station: Station): TimeSeriesPoint[] {
  const points: TimeSeriesPoint[] = [];
  const baseLevel = Math.max(0.4, station.waterLevelM - 0.85);
  const totalPoints = 36; // 3 hours in 5-min intervals (plus 6 future forecast points)
  const startMinutes = 14 * 60; // 14:00 WIB
  for (let i = 0; i < totalPoints; i++) {
    const mins = startMinutes + i * 5;
    const hh = String(Math.floor(mins / 60) % 24).padStart(2, '0');
    const mm = String(mins % 60).padStart(2, '0');
    const progress = i / (totalPoints - 1);
    const wave = Math.sin(i * 0.35) * 0.06;
    const isFuture = i >= 30;
    if (!isFuture) {
      const wl = Number((baseLevel + (station.waterLevelM - baseLevel) * (i / 29) + wave * 0.4).toFixed(2));
      const rain = Number(
        Math.max(0, station.rainfallMmH * (0.4 + 0.6 * Math.sin((i / 29) * Math.PI)) + (i % 3 === 0 ? 1.5 : 0)).toFixed(1)
      );
      const q = Number((12.5 * Math.pow(Math.max(0.2, wl - 0.3), 1.65)).toFixed(1));
      points.push({
        timestamp: `${hh}:${mm}`,
        stationId: station.id,
        waterLevelM: wl,
        waterLevelMdpl: Number((station.elevationMdpl + wl).toFixed(2)),
        rainfallMm: rain,
        dischargeM3s: q,
      });
    } else {
      const stepAhead = i - 29;
      const trendRate = station.fluctuationCmH / 100 / 12; // m per 5 min
      const proj = Number((station.waterLevelM + trendRate * stepAhead * 1.15).toFixed(2));
      const unc = Number((0.05 * stepAhead).toFixed(2));
      points.push({
        timestamp: `${hh}:${mm}`,
        stationId: station.id,
        waterLevelM: station.waterLevelM,
        waterLevelMdpl: Number((station.elevationMdpl + proj).toFixed(2)),
        rainfallMm: Number(Math.max(2, station.rainfallMmH * (1 - stepAhead * 0.08)).toFixed(1)),
        dischargeM3s: Number((12.5 * Math.pow(Math.max(0.2, proj - 0.3), 1.65)).toFixed(1)),
        forecastWaterLevelM: proj,
        uncertaintyPlusMinusM: unc,
      });
    }
    void progress;
  }
  return points;
}

